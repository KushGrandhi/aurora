// Regenerates packages/spec/src/fonts-catalog.ts from Google Fonts' public family list:
//   npx tsx scripts/fonts-catalog.ts [metadata.json]
// Without a file it downloads https://fonts.google.com/metadata/fonts (undocumented; it starts with an XSSI prefix).
import { readFileSync, writeFileSync } from "node:fs";

const raw = process.argv[2] ? readFileSync(process.argv[2], "utf8") : await (await fetch("https://fonts.google.com/metadata/fonts")).text();
const meta = JSON.parse(raw.slice(raw.indexOf("{"))) as { familyMetadataList: { family: string; category: string; fonts: Record<string, unknown>; axes: { tag: string; min: number; max: number }[]; popularity: number; subsets: string[] }[] };
const CAT: Record<string, string> = { "Sans Serif": "sans", Serif: "serif", Display: "display", Handwriting: "hand", Monospace: "mono" };
const rows = meta.familyMetadataList
  .filter((f) => !/icons|symbols/i.test(f.family))
  .map((f) => {
    const keys = Object.keys(f.fonts);
    const wght = f.axes.find((a) => a.tag === "wght");
    const weights = wght ? `${wght.min}..${wght.max}` : [...new Set(keys.map((k) => parseInt(k, 10)))].sort((a, b) => a - b).join(",");
    const italic = keys.some((k) => k.endsWith("i")) ? 1 : 0;
    return [f.family, CAT[f.category] ?? "sans", weights, italic, f.popularity] as const;
  })
  .sort((a, b) => a[4] - b[4]);
const body = rows.map((r) => `  ${JSON.stringify(r)},`).join("\n");
writeFileSync(new URL("../packages/spec/src/fonts-catalog.ts", import.meta.url), `// Generated by scripts/fonts-catalog.ts from Google Fonts' family list. Do not edit.
// [family, category, weights ("100..900" for a variable wght axis, else a list), has italics, popularity rank]
export type FontRow = readonly [string, "sans" | "serif" | "display" | "hand" | "mono", string, 0 | 1, number];
export const FONT_CATALOG: readonly FontRow[] = [
${body}
];
`);
console.log(rows.length, "families");
